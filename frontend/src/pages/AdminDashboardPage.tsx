// Custom pill-style dropdown used for the header filters (date range, risk,
// status). Replaces plain <select> elements so the active choice is always
// visible on the button itself, not just on data further down the page.
function HeaderDropdown<T extends string>({
  value,
  options,
  onChange,
  emphasize,
}: {
  value: T;
  options: { value: T; label: string }[];
  onChange: (v: T) => void;
  emphasize?: boolean;
}) {
  const [open, setOpen] = useState(false);
  const ref = useRef<HTMLDivElement>(null);

  useEffect(() => {
    function onDocClick(e: MouseEvent) {
      if (ref.current && !ref.current.contains(e.target as Node)) setOpen(false);
    }
    document.addEventListener("mousedown", onDocClick);
    return () => document.removeEventListener("mousedown", onDocClick);
  }, []);

  const currentLabel = options.find((o) => o.value === value)?.label ?? value;

  return (
    <div className="relative" ref={ref}>
      <button
        type="button"
        onClick={() => setOpen((o) => !o)}
        className={`flex items-center gap-2 text-sm font-semibold px-3 py-2 rounded-xl border shadow-card transition-colors ${
          emphasize
            ? "bg-primary-50 border-primary-200 text-primary-700 dark:bg-primary-500/15 dark:border-primary-500/40 dark:text-primary-300"
            : "bg-white border-primary-100/70 text-slate-600 dark:bg-[#141a2e] dark:border-white/10 dark:text-slate-200"
        }`}
      >
        {currentLabel}
        <svg
          width="12"
          height="12"
          viewBox="0 0 24 24"
          fill="none"
          stroke="currentColor"
          strokeWidth="2.5"
          strokeLinecap="round"
          strokeLinejoin="round"
          className={`transition-transform ${open ? "rotate-180" : ""}`}
        >
          <path d="M6 9l6 6 6-6" />
        </svg>
      </button>
      {open && (
        <div className="absolute right-0 top-[calc(100%+6px)] min-w-[180px] bg-white dark:bg-[#141a2e] border border-primary-100/70 dark:border-white/10 rounded-xl shadow-soft p-1.5 z-30">
          {options.map((opt) => (
            <button
              key={opt.value}
              type="button"
              onClick={() => {
                onChange(opt.value);
                setOpen(false);
              }}
              className={`block w-full text-left text-sm px-3 py-2 rounded-lg transition-colors ${
                opt.value === value
                  ? "bg-primary-50 text-primary-700 font-semibold dark:bg-primary-500/15 dark:text-primary-300"
                  : "text-slate-600 hover:bg-slate-50 dark:text-slate-300 dark:hover:bg-white/5"
              }`}
            >
              {opt.label}
            </button>
          ))}
        </div>
      )}
    </div>
  );
}

