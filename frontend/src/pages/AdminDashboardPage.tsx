function isoDate(d: Date): string {
  return d.toISOString().slice(0, 10);
}

// Honest, simple trend read: compares the average of the earlier half of the
// selected range to the later half. Returns undefined when there isn't
// enough data to say anything meaningful, rather than inventing a number.
function halfOverHalfDelta(series: number[]): number | undefined {
  if (series.length < 4) return undefined;
  const mid = Math.floor(series.length / 2);
  const avg = (arr: number[]) => arr.reduce((a, b) => a + b, 0) / (arr.length || 1);
  const before = avg(series.slice(0, mid));
  const after = avg(series.slice(mid));
  if (before === 0) return undefined;
  return ((after - before) / before) * 100;
}

// Alert `reason` text is a free-form sentence generated by the risk engine
// (see backend app/ai/risk_engine.py). This buckets it into the short label
// the table/risk-factor widgets show, based on the language the engine
// actually uses for each signal.
function classifyReason(reason: string | null | undefined): string {
  if (!reason) return "Normal";
  const r = reason.toLowerCase();
  if (r.includes("minutes for this customer") || r.includes("velocity")) return "Velocity";
  if (r.includes("device")) return "Device";
  if (r.includes("location")) return "Location";
  if (r.includes("amount") || r.includes("average") || r.includes("spends")) return "Amount";
  if (r.includes("hour")) return "Unusual Hour";
  if (r.includes("new account")) return "New Account";
  return "Normal";
}

